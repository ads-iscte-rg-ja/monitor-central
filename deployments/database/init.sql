CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 email TEXT UNIQUE NOT NULL CHECK(length(email) BETWEEN 1 AND 254),
 notification_email TEXT NOT NULL DEFAULT '', name TEXT NOT NULL DEFAULT '', password_hash TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, last_login_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS audit_log (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 action TEXT NOT NULL, ip_address TEXT, timestamp TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_audit_user_id ON audit_log(user_id);
CREATE INDEX IF NOT EXISTS idx_audit_timestamp ON audit_log(timestamp);
-- Session tokens are random credentials, never sequential entity IDs.
CREATE TABLE IF NOT EXISTS sessions (token TEXT PRIMARY KEY, data BYTEA NOT NULL, expiry TIMESTAMPTZ NOT NULL, user_id BIGINT REFERENCES users(id) ON DELETE CASCADE);
CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expiry ON sessions(expiry);
CREATE TABLE IF NOT EXISTS hosts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL, hostname TEXT NOT NULL, api_key TEXT UNIQUE NOT NULL,
 status TEXT NOT NULL DEFAULT 'unknown' CHECK(status IN ('online','offline','unknown')),
 last_seen_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, demo BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_hosts_last_seen ON hosts(last_seen_at);
CREATE TABLE IF NOT EXISTS machine_stats (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 host_id BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE, source_id BIGINT CHECK(source_id > 0),
 cpu_percent DOUBLE PRECISION NOT NULL CHECK(cpu_percent BETWEEN 0 AND 100),
 ram_used_mb DOUBLE PRECISION NOT NULL CHECK(ram_used_mb >= 0 AND ram_used_mb <= ram_total_mb),
 ram_total_mb DOUBLE PRECISION NOT NULL CHECK(ram_total_mb > 0),
 disk_used_gb DOUBLE PRECISION NOT NULL CHECK(disk_used_gb >= 0 AND disk_used_gb <= disk_total_gb),
 disk_total_gb DOUBLE PRECISION NOT NULL CHECK(disk_total_gb > 0),
 collected_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK(collected_at <= CURRENT_TIMESTAMP),
 UNIQUE(host_id,source_id)
);
CREATE INDEX IF NOT EXISTS idx_machine_stats_host_collected ON machine_stats(host_id,collected_at DESC);
CREATE TABLE IF NOT EXISTS error_logs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 host_id BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE, source_id BIGINT CHECK(source_id > 0),
 app_name TEXT NOT NULL, environment TEXT NOT NULL,
 level TEXT NOT NULL CHECK(level IN ('ERROR','CRITICAL','PANIC','WARN','INFO')),
 message TEXT NOT NULL, stack_trace TEXT, metadata JSONB,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP CHECK(created_at <= CURRENT_TIMESTAMP),
 UNIQUE(host_id,source_id)
);
CREATE INDEX IF NOT EXISTS idx_error_logs_host_created ON error_logs(host_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_error_logs_created_at ON error_logs(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_error_logs_app_name ON error_logs(app_name);
CREATE TABLE IF NOT EXISTS alerts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL,
 host_id BIGINT REFERENCES hosts(id) ON DELETE CASCADE,
 metric TEXT NOT NULL CHECK(metric IN ('cpu','ram','disk','error_rate','error_level','host_offline')),
 condition TEXT NOT NULL CHECK(condition IN ('gt','lt')),
 threshold DOUBLE PRECISION NOT NULL CHECK(threshold > 0 AND threshold < 'Infinity'::DOUBLE PRECISION),
 severity TEXT NOT NULL DEFAULT 'warning' CHECK(severity IN ('warning','critical')),
 notification_channels TEXT[] NOT NULL DEFAULT '{email}', enabled BOOLEAN NOT NULL DEFAULT TRUE,
 system_rule BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_alerts_host_id ON alerts(host_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_alerts_system_host ON alerts(host_id) WHERE system_rule;
CREATE TABLE IF NOT EXISTS alert_events (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 alert_id BIGINT NOT NULL REFERENCES alerts(id) ON DELETE CASCADE, host_id BIGINT NOT NULL REFERENCES hosts(id) ON DELETE CASCADE,
 triggered_value DOUBLE PRECISION NOT NULL, status TEXT NOT NULL DEFAULT 'fired' CHECK(status IN ('fired','acknowledged','resolved')),
 fired_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, resolved_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS idx_alert_events_fired_at ON alert_events(fired_at DESC);
CREATE UNIQUE INDEX IF NOT EXISTS idx_alert_events_open ON alert_events(alert_id,host_id) WHERE status IN ('fired','acknowledged');
CREATE TABLE IF NOT EXISTS email_outbox (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, event_id BIGINT REFERENCES alert_events(id) ON DELETE SET NULL,
 recipient TEXT NOT NULL CHECK(length(recipient) BETWEEN 1 AND 254), subject TEXT NOT NULL, text_body TEXT NOT NULL, html_body TEXT NOT NULL, dedupe_key TEXT UNIQUE NOT NULL,
 attempts INTEGER NOT NULL DEFAULT 0, next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 locked_until TIMESTAMPTZ, sent_at TIMESTAMPTZ, last_error TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_email_outbox_pending ON email_outbox(next_attempt_at,id) WHERE sent_at IS NULL;

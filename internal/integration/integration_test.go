func TestNumericIDsHostScopeAndIdempotency(t *testing.T) {
	db := isolatedDB(t)
	migrate(t, db)
	migrate(t, db)
	ctx := context.Background()
	a, b := host(t, db, "first"), host(t, db, "second")
	if a.ID != 1 || b.ID != 2 {
		t.Fatal("IDs not generated by database")
	}
	s := services.NewIngestionService(repositories.NewMonitoringRepository(db, testHasher(t)))
	input := &models.ErrorLogsRequest{Errors: []models.ErrorLogInput{{ID: 1, AppName: "app", Environment: "test", Level: "ERROR", Message: "failure"}}}
	for _, h := range []*models.Host{a, b} {
		for i := 0; i < 2; i++ {
			accepted, inserted, err := s.IngestErrors(ctx, h.ID, input)
			if err != nil || accepted != 1 || inserted != 1-i {
				t.Fatalf("host %d try %d: %d %d %v", h.ID, i, accepted, inserted, err)
			}
		}
	}
	if count(t, db, "SELECT COUNT(*) FROM error_logs") != 2 {
		t.Fatal("same numeric local ID must not collide across hosts")
	}
	stat := &models.MachineStatsRequest{ID: 1, CPUPercent: 50, RAMUsedMB: 1, RAMTotalMB: 2, DiskUsedGB: 1, DiskTotalGB: 2}
	for i := 0; i < 2; i++ {
		if _, err := s.IngestStats(ctx, a.ID, stat); err != nil {
			t.Fatal(err)
		}
	}
	if count(t, db, "SELECT COUNT(*) FROM machine_stats") != 1 {
		t.Fatal("retry duplicated sample")
	}
	stat.CollectedAt = time.Now().Add(time.Hour)
	if _, err := s.IngestStats(ctx, a.ID, stat); !errors.Is(err, models.ErrFutureTimestamp) {
		t.Fatal("future sample accepted")
	}
	if _, err := db.ExecContext(ctx, `INSERT INTO machine_stats(host_id,cpu_percent,ram_used_mb,ram_total_mb,disk_used_gb,disk_total_gb,collected_at) VALUES($1,1,1,2,1,2,NOW()+INTERVAL '1 day')`, a.ID); err == nil {
		t.Fatal("database future guard missing")
	}
}

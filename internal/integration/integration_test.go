func TestNotificationClaimsAndExpiredLeaseRecovery(t *testing.T) {
	db := isolatedDB(t)
	migrate(t, db)
	ctx := context.Background()
	repo := repositories.NewAlertsRepository(db)
	if err := repo.QueueNotifications(ctx, []models.EmailNotification{{Recipient: "recipient@example.com", Subject: "lease", TextBody: "test", HTMLBody: "test", DedupeKey: "lease-test"}}); err != nil {
		t.Fatal(err)
	}
	var wg sync.WaitGroup
	claims := make(chan *models.EmailNotification, 8)
	errors := make(chan error, 8)
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() { defer wg.Done(); n, err := repo.ClaimNotification(ctx); claims <- n; errors <- err }()
	}
	wg.Wait()
	close(claims)
	close(errors)
	for err := range errors {
		if err != nil {
			t.Fatal(err)
		}
	}
	var claimed *models.EmailNotification
	for n := range claims {
		if n != nil {
			if claimed != nil {
				t.Fatal("two workers claimed the same pending email")
			}
			claimed = n
		}
	}
	if claimed == nil || claimed.Attempts != 1 {
		t.Fatal("notification not claimed")
	}
	if _, err := db.ExecContext(ctx, "UPDATE email_outbox SET locked_until=NOW()-INTERVAL '1 second'"); err != nil {
		t.Fatal(err)
	}
	recovered, err := repo.ClaimNotification(ctx)
	if err != nil || recovered == nil || recovered.ID != claimed.ID || recovered.Attempts != 2 {
		t.Fatal("expired claim not recovered", err)
	}
	if err := repo.CompleteNotification(ctx, claimed.ID, claimed.Attempts, nil); err != nil {
		t.Fatal(err)
	}
	if count(t, db, "SELECT COUNT(*) FROM email_outbox WHERE sent_at IS NOT NULL") != 0 {
		t.Fatal("stale worker completed a newer claim")
	}
	if err := repo.CompleteNotification(ctx, recovered.ID, recovered.Attempts, nil); err != nil {
		t.Fatal(err)
	}
	if count(t, db, "SELECT COUNT(*) FROM email_outbox WHERE sent_at IS NOT NULL") != 1 {
		t.Fatal("current worker could not complete")
	}
}


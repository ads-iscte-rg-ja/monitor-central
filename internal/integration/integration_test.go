func TestAtomicOutboxRollbackConcurrencyAndRetry(t *testing.T) {
	db := isolatedDB(t)
	migrate(t, db)
	ctx := context.Background()
	h := host(t, db, "alerts")
	repo := repositories.NewAlertsRepository(db)
	if _, err := db.ExecContext(ctx, `INSERT INTO users(email,name,password_hash,notification_email) VALUES('a@example.com','a','test','recipient@example.com')`); err != nil {
		t.Fatal(err)
	}
	rule := &models.AlertRule{Name: "CPU", HostID: h.ID, Metric: "cpu", Condition: "gt", Threshold: 80, Severity: "critical", Channels: []string{"email"}, Enabled: true}
	if err := repo.CreateAlert(ctx, rule); err != nil {
		t.Fatal(err)
	}
	newEvent := func() *models.AlertEvent {
		return &models.AlertEvent{AlertID: rule.ID, HostID: h.ID, TriggeredValue: 95, FiredAt: time.Now(), Status: "fired"}
	}
	if _, err := repo.CreateAlertEventWithNotifications(ctx, newEvent(), []models.EmailNotification{{Recipient: "", Subject: "invalid recipient"}}); err == nil {
		t.Fatal("expected invalid outbox row")
	}
	if count(t, db, "SELECT COUNT(*) FROM alert_events") != 0 || count(t, db, "SELECT COUNT(*) FROM email_outbox") != 0 {
		t.Fatal("event/outbox must roll back together")
	}
	var wg sync.WaitGroup
	errs := make(chan error, 8)
	for i := 0; i < 8; i++ {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, err := repo.CreateAlertEventWithNotifications(ctx, newEvent(), []models.EmailNotification{{Recipient: "recipient@example.com", Subject: "CPU", TextBody: "High", HTMLBody: "High"}})
			errs <- err
		}()
	}
	wg.Wait()
	close(errs)
	for err := range errs {
		if err != nil {
			t.Fatal(err)
		}
	}
	if count(t, db, "SELECT COUNT(*) FROM alert_events") != 1 || count(t, db, "SELECT COUNT(*) FROM email_outbox") != 1 {
		t.Fatal("concurrent evaluator duplicated event/outbox")
	}
	mail := &sender{fail: true}
	s := services.NewAlertsService(repo, mail)
	if err := s.DeliverNotifications(ctx); err == nil {
		t.Fatal("expected SMTP failure")
	}
	if count(t, db, "SELECT COUNT(*) FROM email_outbox WHERE sent_at IS NULL AND attempts=1 AND locked_until IS NULL") != 1 {
		t.Fatal("failed email not pending retry")
	}
	mail.fail = false
	if _, err := db.ExecContext(ctx, "UPDATE email_outbox SET next_attempt_at=NOW()"); err != nil {
		t.Fatal(err)
	}
	if err := s.DeliverNotifications(ctx); err != nil {
		t.Fatal(err)
	}
	if mail.calls != 2 || count(t, db, "SELECT COUNT(*) FROM email_outbox WHERE sent_at IS NOT NULL AND attempts=2") != 1 {
		t.Fatal("retry not delivered")
	}
	if err := s.DeliverNotifications(ctx); err != nil || mail.calls != 2 {
		t.Fatal("completed email delivered twice")
	}
	var eventID int64
	if err := db.QueryRow("SELECT id FROM alert_events").Scan(&eventID); err != nil {
		t.Fatal(err)
	}
	if err := repo.AcknowledgeAlertEvent(ctx, eventID); err != nil {
		t.Fatal(err)
	}
	_, open, err := repositories.NewDashboardRepository(db).CountAlerts(ctx)
	if err != nil || open != 1 {
		t.Fatal("acknowledgement hid open incident")
	}
	rule.Enabled = false
	if err := repo.UpdateAlert(ctx, rule); err != nil {
		t.Fatal(err)
	}
	if count(t, db, "SELECT COUNT(*) FROM alert_events WHERE status='resolved'") != 1 {
		t.Fatal("pausing rule did not close event")
	}
}
